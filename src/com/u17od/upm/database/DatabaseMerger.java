package com.u17od.upm.database;

import java.util.HashMap;
import java.util.HashSet;
import java.util.Set;

/**
 * Three-way merge of two diverged password databases against their common base.
 *
 * <p>The base ({@code B}) is the state the two sides last agreed on (the last
 * synchronised database). The merge takes the base, the local ({@code L}) and
 * the remote ({@code R}) databases (all already decrypted) and produces a
 * merged database in which neither side's edits are silently lost.
 *
 * <p>Accounts are keyed by name. For every name in {@code union(B, L, R)} the
 * result is chosen so that:
 * <ul>
 *   <li>a side that did not touch an account always defers to the side that
 *       did;</li>
 *   <li>a genuine conflict (both sides edited the same account, or both added
 *       the same name differently) keeps the local account under its original
 *       name and preserves the remote account as a copy named
 *       {@code "<name> (remote)"};</li>
 *   <li>delete-vs-edit keeps the edited side, because an edit is stronger
 *       recent intent than a deletion and this never drops edited data.</li>
 * </ul>
 *
 * <p>{@code DatabaseOptions} (remote location / auth entry) describe how this
 * device reaches the server and are therefore always taken from the local
 * database, never from the remote copy.
 *
 * <p>This class is a pure function over decrypted data: it performs no I/O and
 * no cryptography. It is fully covered by {@code DatabaseMergerTest}.
 */
