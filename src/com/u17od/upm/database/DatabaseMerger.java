public final class DatabaseMerger {

    /** Suffix appended to a conflicting remote account. */
    public static final String REMOTE_SUFFIX = " (remote)";

    private DatabaseMerger() {
    }

    /**
     * Merge {@code local} and {@code remote} against their common {@code base}.
     *
     * @param base   the last-synchronised state, may be {@code null} (treated
     *               as empty, though callers normally handle the no-base case
     *               with a last-writer-wins fallback instead).
     * @param local  the device database.
     * @param remote the downloaded database.
     * @return the merged database plus statistics.
     */
    public static MergeResult merge(PasswordDatabase base, PasswordDatabase local,
            PasswordDatabase remote) {

        HashMap<String, AccountInformation> b = toMap(base);
        HashMap<String, AccountInformation> l = toMap(local);
        HashMap<String, AccountInformation> r = toMap(remote);

        // The merged database reuses the local encryption service so the file
        // keeps the local salt and stays decryptable with the same password.
        PasswordDatabase merged = new PasswordDatabase(local.getEncryptionService(),
                copyOf(local.getDbOptions()));

        int conflicts = 0;

        // Names already in use by any of the three inputs. Used to guarantee a
        // "(remote)" copy never collides with an existing account, regardless
        // of the order in which the names are processed.
        Set<String> reservedNames = new HashSet<String>();
        reservedNames.addAll(b.keySet());
        reservedNames.addAll(l.keySet());
        reservedNames.addAll(r.keySet());

        Set<String> names = new HashSet<String>(reservedNames);

        for (String name : names) {
            AccountInformation bi = b.get(name);
            AccountInformation li = l.get(name);
            AccountInformation ri = r.get(name);

            boolean inB = bi != null;
            boolean inL = li != null;
            boolean inR = ri != null;

            if (!inB) {
                if (inL && inR) {
                    if (li.equals(ri)) {
                        merged.addAccount(li);              // both added identically
                    } else {
                        merged.addAccount(li);              // both added differently -> conflict
                        merged.addAccount(renamedCopy(ri, reservedNames));
                        conflicts++;
                    }
                } else if (inL) {
                    merged.addAccount(li);                  // added locally
                } else if (inR) {
                    merged.addAccount(ri);                  // added remotely
                }
            } else if (inL && inR) {
                if (li.equals(ri)) {
                    merged.addAccount(li);                  // unchanged / converged
                } else if (li.equals(bi)) {
                    merged.addAccount(ri);                  // remote edited only
                } else if (ri.equals(bi)) {
                    merged.addAccount(li);                  // local edited only
                } else {
                    merged.addAccount(li);                  // both edited -> conflict
                    merged.addAccount(renamedCopy(ri, reservedNames));
                    conflicts++;
                }
            } else if (inL) {
                // Present in base and local, gone from remote.
                if (!li.equals(bi)) {
                    merged.addAccount(li);                  // delete vs edit -> keep the edit
                }
                // else: deleted remotely, nothing to add.
            } else if (inR) {
                // Present in base and remote, gone from local.
                if (!ri.equals(bi)) {
                    merged.addAccount(ri);                  // delete vs edit -> keep the edit
                }
                // else: deleted locally, nothing to add.
            }
            // else: deleted on both sides -> drop.
        }

        int newRevision = Math.max(local.getRevision(), remote.getRevision()) + 1;
        merged.setRevision(newRevision);

        boolean uploadRequired = !accountsEqual(merged, remote);

        return new MergeResult(merged, uploadRequired, merged.getAccounts().size(), conflicts);
    }

    /**
     * Build a copy of {@code source} under a fresh name of the form
     * {@code "<name> (remote)"}, appending a number if that name is already
     * taken (e.g. {@code "<name> (remote 2)"}). The chosen name is added to
     * {@code reservedNames} so subsequent copies don't reuse it.
     */
    private static AccountInformation renamedCopy(AccountInformation source,
            Set<String> reservedNames) {
        String name = source.getAccountName() + REMOTE_SUFFIX;
        int n = 1;
        while (reservedNames.contains(name)) {
            n++;
            name = source.getAccountName() + " (remote " + n + ")";
        }
        reservedNames.add(name);
        return new AccountInformation(name, source.getUserId(), source.getPassword(),
                source.getUrl(), source.getNotes());
    }

    private static HashMap<String, AccountInformation> toMap(PasswordDatabase db) {
        HashMap<String, AccountInformation> map = new HashMap<String, AccountInformation>();
        if (db != null) {
            for (AccountInformation ai : db.getAccounts()) {
                map.put(ai.getAccountName(), ai);
            }
        }
        return map;
    }

    private static DatabaseOptions copyOf(DatabaseOptions options) {
        DatabaseOptions copy = new DatabaseOptions();
        copy.setRemoteLocation(options.getRemoteLocation());
        copy.setAuthDBEntry(options.getAuthDBEntry());
        return copy;
    }

    /**
     * True when two databases hold exactly the same accounts (name and all
     * five fields), ignoring {@link DatabaseOptions}. Used by the sync flow to
     * tell "up to date" apart from "only the remote changed".
     */
    public static boolean accountsEqual(PasswordDatabase a, PasswordDatabase b) {
        if (a.getAccounts().size() != b.getAccounts().size()) {
            return false;
        }
        for (AccountInformation account : a.getAccounts()) {
            AccountInformation other = b.getAccount(account.getAccountName());
            if (other == null || !account.equals(other)) {
                return false;
            }
        }
        return true;
    }

    /**
     * The outcome of a {@link DatabaseMerger#merge} call.
     */
    public static final class MergeResult {

        private final PasswordDatabase merged;
        private final boolean uploadRequired;
        private final int accountCount;
        private final int conflictCount;

        MergeResult(PasswordDatabase merged, boolean uploadRequired, int accountCount,
                int conflictCount) {
            this.merged = merged;
            this.uploadRequired = uploadRequired;
            this.accountCount = accountCount;
            this.conflictCount = conflictCount;
        }

        /** The merged database (file-less; set its file before saving). */
        public PasswordDatabase getMerged() {
            return merged;
        }

        /**
         * True when the merged result differs from the remote database and
         * must therefore be uploaded. False means the remote already contains
         * everything (only the remote changed, or both sides are equal).
         */
        public boolean isUploadRequired() {
            return uploadRequired;
        }

        /** Number of accounts in the merged database. */
        public int getAccountCount() {
            return accountCount;
        }

        /** Number of conflicts preserved as "(remote)" copies. */
        public int getConflictCount() {
            return conflictCount;
        }
    }
}
