package com.u17od.upm;

import java.io.File;
import java.io.IOException;
import java.security.GeneralSecurityException;
import java.util.Date;

import javax.crypto.SecretKey;

import android.app.Activity;
import android.content.Intent;
import android.util.Log;

import com.u17od.upm.crypto.InvalidPasswordException;
import com.u17od.upm.database.DatabaseMerger;
import com.u17od.upm.database.PasswordDatabase;
import com.u17od.upm.database.ProblemReadingDatabaseFile;


public abstract class SyncDatabaseActivity extends Activity {

    private static final int ENTER_PW_REQUEST_CODE = 222;
    public static final int SYNC_DB_REQUEST_CODE = 226;

    public static final int RESULT_REFRESH = 1;

    public static interface SyncResult {
        public static final int IN_SYNC = 0;
        public static final int UPLOAD_LOCAL = 1;
        public static final int KEEP_REMOTE = 2;
    }

    protected File downloadedDatabaseFile;

    protected abstract void uploadDatabase();
    protected abstract void downloadDatabase();

    protected void decryptDatabase() {
        SecretKey existingDBSecretKey = getPasswordDatabase().getEncryptionService().getSecretKey();
        try {
            PasswordDatabase passwordDatabase = null;
            if (downloadedDatabaseFile != null) {
                passwordDatabase = new PasswordDatabase(downloadedDatabaseFile, existingDBSecretKey);
            }
            syncDb(passwordDatabase);
        } catch (IOException e) {
            Log.e("SyncDatabaseActivity.onCreate()", "Problem reading database", e);
            UIUtilities.showToast(SyncDatabaseActivity.this, R.string.problem_reading_upm_db, true);
            finish();
        } catch (GeneralSecurityException e) {
            Log.e("SyncDatabaseActivity.onCreate()", "Problem decrypting database", e);
            UIUtilities.showToast(SyncDatabaseActivity.this, R.string.problem_decrypying_db, true);
            finish();
        } catch (ProblemReadingDatabaseFile e) {
            Log.e("SyncDatabaseActivity.onCreate()", "Not a password database", e);
            UIUtilities.showToast(SyncDatabaseActivity.this, R.string.not_password_database);
            finish();
        } catch (InvalidPasswordException e) {
            EnterMasterPassword.databaseFileToDecrypt = downloadedDatabaseFile;
            Intent i = new Intent(SyncDatabaseActivity.this, EnterMasterPassword.class);
            startActivityForResult(i, ENTER_PW_REQUEST_CODE);
        }
    }

    @Override
    protected void onActivityResult(int requestCode, int resultCode, Intent intent) {
        switch(requestCode) {
            case ENTER_PW_REQUEST_CODE:
                if (resultCode == Activity.RESULT_CANCELED) {
                    UIUtilities.showToast(this, R.string.enter_password_cancalled);
                    finish();
                } else {
                    syncDb(EnterMasterPassword.decryptedPasswordDatabase);
                }
                break;
        }
    }

    // START modification - generated by AI (GitHub Copilot, DeepSeek V4 Flash)
    /**
     * Decide what to do with a freshly downloaded remote database.
     *
     * <p>When a usable sync base exists, the local and remote databases are
     * three-way merged (see {@link DatabaseMerger}) so neither side's edits are
     * lost. When there is no usable base we fall back to the old
     * last-writer-wins behaviour, but first keep an encrypted copy of the side
     * that loses so nothing is silently discarded.
     */
    protected int syncDb(PasswordDatabase remote) {
        int syncResult = SyncResult.IN_SYNC;
        UPMApplication app = (UPMApplication) getApplication();
        PasswordDatabase local = app.getPasswordDatabase();

        if (remote == null) {
            // No remote database yet -> create it from the local one. The base
            // is recorded by onUploadSucceeded() once the upload has worked.
            uploadDatabase();
            syncResult = SyncResult.UPLOAD_LOCAL;
        } else {
            PasswordDatabase base = loadSyncBase(app);
            if (base == null) {
                syncResult = syncDbLastWriterWins(app, local, remote);
            } else {
                syncResult = syncDbMerge(app, base, local, remote);
            }
        }

        app.setTimeOfLastSync(new Date());
        if (downloadedDatabaseFile != null) {
            downloadedDatabaseFile.delete();
        }
        return syncResult;
    }

    /**
     * Load the last-synchronised database used as the merge base, or null if it
     * is missing or cannot be decrypted with the current key (e.g. first sync
     * after install, or after a master-password change).
     */
    private PasswordDatabase loadSyncBase(UPMApplication app) {
        File baseFile = Utilities.getSyncBaseFile(this);
        if (!baseFile.exists()) {
            return null;
        }
        try {
            SecretKey secretKey = app.getPasswordDatabase().getEncryptionService().getSecretKey();
            return new PasswordDatabase(baseFile, secretKey);
        } catch (Exception e) {
            Log.w("SyncDatabaseActivity", "Sync base unusable, falling back to last-writer-wins", e);
            return null;
        }
    }

    private int syncDbMerge(UPMApplication app, PasswordDatabase base, PasswordDatabase local,
            PasswordDatabase remote) {
        DatabaseMerger.MergeResult merge = DatabaseMerger.merge(base, local, remote);

        if (merge.isUploadRequired()) {
            // Local changes (edits, additions, deletions) and/or conflicts must
            // be published. Persist the merged db and upload it. The base file
            // is written by onUploadSucceeded() once the upload has succeeded.
            PasswordDatabase merged = merge.getMerged();
            merged.setDatabaseFile(Utilities.getDatabaseFile(this));
            try {
                synchronized (UPMApplication.sDataLock) {
                    merged.save();
                }
            } catch (Exception e) {
                Log.e("SyncDatabaseActivity", "Problem saving merged database", e);
                UIUtilities.showToast(this, R.string.generic_error, true);
                finish();
                return SyncResult.IN_SYNC;
            }
            app.setPasswordDatabase(merged);
            setResult(RESULT_REFRESH);

            if (merge.getConflictCount() > 0) {
                UIUtilities.showToast(this,
                        getString(R.string.sync_conflicts_kept, merge.getConflictCount()), true);
            } else {
                UIUtilities.showToast(this, R.string.sync_merged);
            }

            uploadDatabase();
            return SyncResult.UPLOAD_LOCAL;
        }

        if (DatabaseMerger.accountsEqual(local, remote)) {
            // Both sides already agree -> nothing to transfer.
            Utilities.saveSyncBase(this, Utilities.getDatabaseFile(this));
            UIUtilities.showToast(this, R.string.db_uptodate);
            finish();
            return SyncResult.IN_SYNC;
        }

        // Only the remote changed (local == base) -> take the remote copy.
        keepRemote(app, remote);
        return SyncResult.KEEP_REMOTE;
    }

    /**
     * Fallback used when no merge base is available: the old last-writer-wins
     * comparison, with an encrypted copy of the losing side kept on disk.
     */
    private int syncDbLastWriterWins(UPMApplication app, PasswordDatabase local,
            PasswordDatabase remote) {
        Log.w("SyncDatabaseActivity", "No sync base; using last-writer-wins fallback");
        if (remote.getRevision() < local.getRevision()) {
            // Local wins; keep a copy of the remote we're about to overwrite.
            backupConflictCopy(downloadedDatabaseFile);
            uploadDatabase();
            return SyncResult.UPLOAD_LOCAL;
        } else if (remote.getRevision() > local.getRevision()) {
            // Remote wins; keep a copy of the local we're about to overwrite.
            backupConflictCopy(Utilities.getDatabaseFile(this));
            keepRemote(app, remote);
            return SyncResult.KEEP_REMOTE;
        } else {
            Utilities.saveSyncBase(this, Utilities.getDatabaseFile(this));
            UIUtilities.showToast(this, R.string.db_uptodate);
            finish();
            return SyncResult.IN_SYNC;
        }
    }

    /**
     * Make the downloaded remote database the local one. Afterwards the local
     * file is the state both sides agree on, so it becomes the new sync base.
     */
    private void keepRemote(UPMApplication app, PasswordDatabase remote) {
        app.copyFile(downloadedDatabaseFile, Utilities.getDatabaseFile(this), this);
        app.setPasswordDatabase(remote);
        remote.setDatabaseFile(Utilities.getDatabaseFile(this));

        Utilities.saveSyncBase(this, Utilities.getDatabaseFile(this));

        setResult(RESULT_REFRESH);
        UIUtilities.showToast(this, R.string.new_db_downloaded);

        // Ask the BackupManager to backup the database using
        // Google's cloud backup service.
        Log.i("SyncDatabaseActivity", "Calling BackupManager().dataChanged()");
        app.getBackupManager().dataChanged();

        finish();
    }

    private void backupConflictCopy(File source) {
        if (source == null || !source.exists()) {
            return;
        }
        File backup = Utilities.getConflictBackupFile(this);
        if (!((UPMApplication) getApplication()).copyFile(source, backup, this)) {
            Log.w("SyncDatabaseActivity", "Could not write conflict backup to " + backup);
        }
    }

    /**
     * Called by the transport upload tasks after the database has been
     * successfully pushed to the remote. The just-uploaded local database is
     * the state both sides now agree on, so it becomes the new sync base.
     */
    protected void onUploadSucceeded() {
        if (!Utilities.saveSyncBase(this, Utilities.getDatabaseFile(this))) {
            Log.w("SyncDatabaseActivity", "Could not update the sync base file");
        }
    }
    // END modification - generated by AI (GitHub Copilot, DeepSeek V4 Flash)

    protected PasswordDatabase getPasswordDatabase() {
        return ((UPMApplication) getApplication()).getPasswordDatabase();
    }

}
