    private static PasswordDatabase db(int revision, AccountInformation... accounts)
            throws Exception {
        PasswordDatabase db = new PasswordDatabase(new EncryptionService(PASSWORD),
                new DatabaseOptions());
        db.setRevision(revision);
        for (AccountInformation ai : accounts) {
            db.addAccount(ai);
        }
        return db;
    }

    private static AccountInformation acc(String name, String password) {
        return new AccountInformation(name, name + "-user", password,
                "https://" + name + ".example", "notes for " + name);
    }

    /** An account with the same fields as {@code source} but a different name. */
    private static AccountInformation copyAs(String name, AccountInformation source) {
        return new AccountInformation(name, source.getUserId(), source.getPassword(),
                source.getUrl(), source.getNotes());
    }
